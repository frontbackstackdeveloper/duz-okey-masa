import assert from "node:assert/strict";
import { newGame, start, draw, discard, advanceBot, isWinning, info, view } from "../lib/game.ts";

const g = newGame("ABCDEFGH", "Tamer", "host");
g.seats.push({ name: "Arkadaş", token: "friend", bot: false, hand: [] });
start(g);
assert.equal(g.seats.length, 4);
assert.equal(g.seats[0].hand.length, 15);
assert.equal(g.seats[1].hand.length, 14);
assert.equal(new Set([g.indicator, ...g.wall, ...g.seats.flatMap(s => s.hand)]).size, 106);
discard(g, 0, g.seats[0].hand[0]);
assert.equal(g.turn, 1);
draw(g, 1, "wall");
assert.equal(g.seats[1].hand.length, 15);
discard(g, 1, g.seats[1].hand[0]);
assert.equal(g.turn, 2);
advanceBot(g);
assert.equal(g.turn, 3);
assert.equal(g.lastMove?.seat, 2);
advanceBot(g);
assert.equal(g.turn, 0);
assert.equal(g.stage, "draw");
assert.equal(g.seats[0].hand.length, 14);
assert.equal(view(g, "host").discardPiles.length, 4);
const claimed = newGame("ZXCVBNMK", "Tamer", "host");
claimed.seats.push({ name: "Arkadaş", token: "friend", bot: false, hand: [] });
start(claimed);
const offered = claimed.seats[0].hand[0];
discard(claimed, 0, offered);
draw(claimed, 1, "discard");
assert.equal(claimed.discards.at(-1)?.taken, true);
assert.equal(claimed.lastDiscard, null);
const testGame = { jokerColor: 3, jokerNumber: 13 };
const blackNineGame = { jokerColor: 3, jokerNumber: 9 };
const allTiles = Array.from({ length: 106 }, (_, i) => i);
assert.equal(allTiles.filter(t => info(t, blackNineGame).joker).length, 2);
assert.equal(allTiles.filter(t => info(t, blackNineGame).falseJoker).length, 2);
// Seven pairs, including a false joker as the indicated 13.
const pairs = [0, 52, 1, 53, 2, 54, 13, 65, 14, 66, 26, 78, 39, 91];
assert.equal(isWinning(pairs, testGame), true);
const groups = [0, 1, 2, 13, 14, 15, 26, 27, 28, 39, 40, 41, 42, 104];
assert.equal(isWinning(groups, testGame), false);
const winning = newGame("WINROOM1", "Tamer", "host");
winning.phase = "playing"; winning.stage = "discard"; winning.turn = 0;
winning.jokerColor = 3; winning.jokerNumber = 13;
winning.seats[0].hand = [...pairs, 3];
discard(winning, 0, 3);
assert.equal(winning.phase, "finished");
assert.equal(winning.winner, 0);
assert.match(winning.result, /Tamer/);
// Screenshot regression: three color groups plus black 10-11-12-13-1.
const screenshotHand = [16, 42, 3, 12, 25, 38, 20, 33, 7, 48, 49, 50, 51, 39];
const screenshotGame = newGame("SCREEN01", "Arkadaş", "friend");
screenshotGame.jokerColor = 2;
screenshotGame.jokerNumber = 3;
assert.equal(isWinning(screenshotHand, screenshotGame), true);
screenshotGame.phase = "playing"; screenshotGame.stage = "discard"; screenshotGame.turn = 0;
screenshotGame.seats[0].hand = [...screenshotHand, 1];
discard(screenshotGame, 0, 1);
assert.equal(screenshotGame.phase, "finished");
assert.equal(screenshotGame.winner, 0);
assert.match(screenshotGame.result, /Arkadaş/);
// Wrapping must stop at 1; 13-1-2 is not a run.
const invalidWrap = [3, 16, 29, 4, 17, 30, 45, 46, 47, 48, 49, 51, 39, 40];
assert.equal(isWinning(invalidWrap, screenshotGame), false);
console.log("Game rules and two-player bot flow OK");
