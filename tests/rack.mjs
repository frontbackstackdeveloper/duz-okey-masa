import assert from "node:assert/strict";
import { arrangeRack, moveRackTile, reconcileRack, RACK_COLUMNS, RACK_SLOTS } from "../lib/rack.ts";

const hand = Array.from({ length: 15 }, (_, i) => i);
const initial = reconcileRack(null, hand);
assert.equal(initial.length, RACK_SLOTS);
assert.equal(initial.slice(0, RACK_COLUMNS).filter(x => x !== null).length, 8);
assert.equal(initial.slice(RACK_COLUMNS).filter(x => x !== null).length, 7);
assert.deepEqual(initial.filter(x => x !== null).sort((a, b) => a - b), hand);
const moved = moveRackTile(initial, 0, 9);
assert.equal(moved[9], 0);
assert.equal(moved[0], null);
const afterDiscard = reconcileRack(moved, hand.slice(1));
assert.equal(afterDiscard.includes(0), false);
const afterDraw = reconcileRack(afterDiscard, [...hand.slice(1), 99], 19);
assert.equal(afterDraw[19], 99);
assert.equal(new Set(afterDraw.filter(x => x !== null)).size, 15);
const placedOnTile = reconcileRack(initial, [...hand, 99], 0);
assert.equal(placedOnTile[0], 99);
assert.equal(placedOnTile.filter(x => x === 0).length, 1);
const edgeRack = Array.from({ length: RACK_SLOTS }, () => null);
edgeRack[19] = 7;
const edgePlaced = reconcileRack(edgeRack, [7, 6], 19);
assert.equal(edgePlaced[19], 6);
assert.equal(edgePlaced[18], 7);
const gapRack = Array.from({ length: RACK_SLOTS }, () => null);
gapRack[0] = 4; gapRack[1] = 5; gapRack[2] = 7; gapRack[5] = 6;
const inserted = moveRackTile(gapRack, 5, 2);
assert.deepEqual(inserted.slice(0, 4), [4, 5, 6, 7]);
assert.equal(inserted.filter(x => x === 6).length, 1);
const sorted = arrangeRack([5, 3, 4], (a, b) => a - b);
assert.deepEqual(sorted.filter(x => x !== null), [3, 4, 5]);
console.log("Two-row rack placement and persistence rules OK");
